@dataclass
class PriceSnapshot:
    """Lightweight price snapshot — replaces deepcopy of full MarketData"""
    market_id: str
    prices: Dict[str, float]
    last_update: datetime


class BaseStrategy:
    """Base class for trading strategies"""

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.logger = logging.getLogger(__name__)
        # deque(maxlen=30) auto-evicts old entries — no manual slicing, O(1) append
        self.market_history: Dict[str, deque] = {}

    def update_market_data(self, market: MarketData):
        """Store a lightweight price snapshot — avoids deepcopy overhead"""
        if market.market_id not in self.market_history:
            self.market_history[market.market_id] = deque(maxlen=30)
        self.market_history[market.market_id].append(
            PriceSnapshot(
                market_id=market.market_id,
                prices=dict(market.prices),   # shallow copy — only the dict
                last_update=market.last_update,
            )
        )
    
    def generate_signals(self, markets: List[MarketData]) -> List[TradeSignal]:
        """Generate trading signals - override in subclass"""
        raise NotImplementedError


class MomentumStrategy(BaseStrategy):
    """
    Simple momentum strategy for 5-minute markets
    - Buys when price is rising quickly
    - Sells when price is falling quickly
    """
    
    def generate_signals(self, markets: List[MarketData]) -> List[TradeSignal]:
        signals = []
        
        for market in markets:
            self.update_market_data(market)
            
            # Need at least 3 data points for momentum
            if len(self.market_history.get(market.market_id, [])) < 3:
                continue
            
            history = self.market_history[market.market_id]
            
            for outcome in market.outcomes:
                signal = self._check_momentum(market, outcome, history)
                if signal:
                    signals.append(signal)
        
        return signals
    
    def _check_momentum(self, market: MarketData, outcome: str,
                       history) -> Optional[TradeSignal]:
        """Check if there's momentum signal for this outcome"""

        prices = [s.prices.get(outcome, 0.0) for s in history][-5:]

        if len(prices) < 3:
            return None

        base = prices[-3]
        recent_change = (prices[-1] - base) / base if base > 0 else 0.0
        
        # Thresholds from config
        buy_threshold = self.config.get('momentum_buy_threshold', 0.05)  # 5% rise
        sell_threshold = self.config.get('momentum_sell_threshold', -0.05)  # 5% fall
        min_confidence = self.config.get('min_confidence', 0.6)
        
        # Generate signals
        if recent_change > buy_threshold:
            confidence = min(0.9, 0.5 + abs(recent_change) * 5)
            if confidence >= min_confidence:
                return TradeSignal(
                    market_id=market.market_id,
                    outcome=outcome,
                    action=OrderSide.BUY,
                    confidence=confidence,
                    size=self._calculate_position_size(confidence),
                    target_price=prices[-1] * 1.01,  # Slight premium
                    reason=f"Momentum buy: {recent_change:.1%} price increase",
                    timestamp=datetime.now()
                )
        
        elif recent_change < sell_threshold:
            confidence = min(0.9, 0.5 + abs(recent_change) * 5)
            if confidence >= min_confidence:
                return TradeSignal(
                    market_id=market.market_id,
                    outcome=outcome,
                    action=OrderSide.SELL,
                    confidence=confidence,
                    size=self._calculate_position_size(confidence),
                    target_price=prices[-1] * 0.99,  # Slight discount
                    reason=f"Momentum sell: {recent_change:.1%} price decrease",
                    timestamp=datetime.now()
                )
        
        return None
    
    def _calculate_position_size(self, confidence: float) -> float:
        """Calculate position size based on confidence"""
        base_size = self.config.get('base_position_size', 10.0)  # $10 base
        max_size = self.config.get('max_position_size', 100.0)   # $100 max
        
        # Scale with confidence
        size = base_size * (1 + confidence)
        return min(size, max_size)



class PolymarketAgent:
    """
    Main trading agent that coordinates all components
    """
    
    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.logger = self._setup_logging()
        
        # Initialize components
        self.client = PolymarketClient(
            api_key=config['api_key'],
            api_secret=config['api_secret'],
            testnet=config.get('testnet', True)
        )
        
        # Choose strategy
        strategy_name = config.get('strategy', 'momentum')
        if strategy_name == 'momentum':
            self.strategy = MomentumStrategy(config.get('strategy_config', {}))
        else:
            raise ValueError(f"Unknown strategy: {strategy_name}")
        
        self.risk_manager = RiskManager(config.get('risk_config', {}))
        
        # State
        self.running = False
        self.positions: List[Position] = []
        self.pending_orders: List[Order] = []
        
    def _setup_logging(self) -> logging.Logger:
        """Setup logging configuration"""
        logging.basicConfig(
            level=logging.INFO,
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
            handlers=[
                logging.FileHandler('polymarket_agent.log'),
                logging.StreamHandler()
            ]
        )
        return logging.getLogger(__name__)
    
    async def start(self):
        """Start the trading agent"""
        self.logger.info("=" * 80)
        self.logger.info("Starting Polymarket Trading Agent")
        self.logger.info("=" * 80)
        self.logger.info(f"Strategy: {self.config.get('strategy')}")
        self.logger.info(f"Testnet: {self.config.get('testnet', True)}")
        self.logger.info(f"Update interval: {self.config.get('update_interval_seconds', 10)}s")
        
        self.running = True
        
        async with self.client:
            while self.running:
                try:
                    await self._trading_loop()
                    await asyncio.sleep(self.config.get('update_interval_seconds', 10))
                except Exception as e:
                    self.logger.error(f"Error in trading loop: {e}", exc_info=True)
                    await asyncio.sleep(5)
    
    async def _trading_loop(self):
        """Main trading loop iteration"""
        
        # 1. Fetch current markets
        markets = await self.client.get_markets()
        self.logger.info(f"Monitoring {len(markets)} markets")
        
        # 2. Update positions
        self.positions = await self.client.get_positions()
        
        # 3. Generate trading signals
        signals = self.strategy.generate_signals(markets)
        self.logger.info(f"Generated {len(signals)} trading signals")
        
        # 4. Execute approved signals
        for signal in signals:
            await self._execute_signal(signal)
        
        # 5. Monitor and manage existing positions
        await self._manage_positions()
    
    async def _execute_signal(self, signal: TradeSignal):
        """Execute a trading signal if it passes risk checks"""
        
        # Convert signal to order
        order = Order(
            market_id=signal.market_id,
            outcome=signal.outcome,
            side=signal.action,
            size=signal.size,
            price=signal.target_price,
            timestamp=datetime.now()
        )
        
        # Risk check
        approved, reason = self.risk_manager.check_order(order, self.positions)
        
        if not approved:
            self.logger.warning(f"Order rejected: {reason}")
            return
        
        # Place order
        self.logger.info(f"Executing signal: {signal.reason}")
        order_id = await self.client.place_order(order)
        
        if order_id:
            order.order_id = order_id
            self.pending_orders.append(order)
            self.logger.info(f"Order placed: {order_id}")
        else:
            self.logger.error("Failed to place order")
    
    async def _manage_positions(self):
        """Monitor and manage existing positions"""
        
        for position in self.positions:
            # Check stop loss
            stop_loss_pct = self.config.get('risk_config', {}).get('stop_loss_pct', 0.10)
            
